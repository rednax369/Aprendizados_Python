# Mostra na tela o texto: Minha primeira aula de python
print('Minha primeira aula de python')

# TRABALHANDO COM O COMANDO PRINT

# Soma 5 + 9 e mostra o resultado: 14
print(5 + 9)

# Repete o texto 'Xander ' cinco vezes
print('Xander ' * 5)

# Multiplica 5 por 6 e mostra o resultado: 30
print(5 * 6)

# '5' está entre aspas, então é texto e é repetido 10 vezes: 5555555555
print('5' * 10)

# TRABALHANDO COM CONCATENAÇÃO

# Cria a variável "nome" com o texto 'Xander'
nome = 'Xander'

# Mostra o valor da variável: Xander
print(nome)

# Troca o valor de "nome" para 'Lucas'
nome = 'Lucas'

# Mostra o novo valor: Lucas
print(nome)

# end=' ' troca a quebra de linha por um espaço, então o próximo print continua na mesma linha
print('Parabéns pra você,', end=' ')

# Resultado: Parabéns pra você, Nesta data querida
print('Nesta data querida')

# A vírgula adiciona um espaço automaticamente: A soma é 10
print('A soma é', 10)

# Concatenação com +: o espaço foi colocado dentro do texto. Resultado: A soma é 10
print('A soma é ' + '10')